#!/usr/bin/env python3
"""Synthetic append-only local HLS EVENT refresh proof with actual libmpv.

No remote URL, credentials, media export or device write. The fixture is
generated by the existing host demux integration test and copied into a
private temporary directory. Proves growing local video timeline behavior,
not physical Switch output or real-time buffering/network resilience.
"""
from __future__ import annotations
import ctypes
import ctypes.util
import pathlib
import re
import shutil
import sys
import tempfile
import time

from m3_live_libmpv_check import Node, NodeList, NodeValue, Event


def check_ready(ready: pathlib.Path, upstream: pathlib.Path) -> bool:
    libname=ctypes.util.find_library("mpv")
    if not libname:return False
    clips=sorted(ready.glob("v_*.ts"))
    data=upstream.read_text()
    durations=[float(v) for v in re.findall(r"(?m)^#EXTINF:([0-9.]+),",data)]
    if len(clips)<5 or len(clips)!=len(durations):return False
    with tempfile.TemporaryDirectory(prefix="ttnx-event-playback-") as temp:
        root=pathlib.Path(temp)
        audio=root/"external_audio.m4a"
        shutil.copyfile(ready/"external_audio.m4a",audio)
        manifest=root/"video.m3u8"
        master=root/"master.m3u8"
        master.write_text("#EXTM3U\n#EXT-X-VERSION:7\n"
                          "#EXT-X-STREAM-INF:BANDWIDTH=1500000\nvideo.m3u8\n")
        def snapshot(count: int,finished: bool=False):
            header=("#EXTM3U\n#EXT-X-VERSION:7\n"
                    "#EXT-X-PLAYLIST-TYPE:EVENT\n"
                    "#EXT-X-MEDIA-SEQUENCE:0\n"
                    f"#EXT-X-TARGETDURATION:{max(1,int(max(durations)+.999))}\n")
            lines="".join(
                f"#EXTINF:{durations[i]:.3f},\nv_{i:05d}.ts\n"
                for i in range(count))
            incoming=manifest.with_suffix(".pending")
            incoming.write_text(header+lines+
                                ("#EXT-X-ENDLIST\n" if finished else ""))
            incoming.replace(manifest)
        for clip in clips[:2]:shutil.copyfile(clip,root/clip.name)
        snapshot(2)
        lib=ctypes.CDLL(libname)
        lib.mpv_create.restype=ctypes.c_void_p
        lib.mpv_set_option_string.argtypes=[
            ctypes.c_void_p,ctypes.c_char_p,ctypes.c_char_p]
        lib.mpv_set_option_string.restype=ctypes.c_int
        lib.mpv_set_option.argtypes=[
            ctypes.c_void_p,ctypes.c_char_p,ctypes.c_int,ctypes.c_void_p]
        lib.mpv_set_option.restype=ctypes.c_int
        lib.mpv_initialize.argtypes=[ctypes.c_void_p]
        lib.mpv_initialize.restype=ctypes.c_int
        lib.mpv_command.argtypes=[ctypes.c_void_p,
                                  ctypes.POINTER(ctypes.c_char_p)]
        lib.mpv_command.restype=ctypes.c_int
        lib.mpv_wait_event.argtypes=[ctypes.c_void_p,ctypes.c_double]
        lib.mpv_wait_event.restype=ctypes.POINTER(Event)
        lib.mpv_get_property.argtypes=[
            ctypes.c_void_p,ctypes.c_char_p,ctypes.c_int,ctypes.c_void_p]
        lib.mpv_get_property.restype=ctypes.c_int
        lib.mpv_terminate_destroy.argtypes=[ctypes.c_void_p]
        handle=lib.mpv_create()
        if not handle:return False
        try:
            for key,value in (
                ("config","no"),("vo","null"),("ao","null"),("hwdec","no"),
                ("demuxer-lavf-o","protocol_whitelist=file")):
                if lib.mpv_set_option_string(
                        handle,key.encode(),value.encode())<0:return False
            raw=str(audio).encode()
            node=Node(NodeValue(string=raw),1)
            arr=(Node*1)(node)
            nl=NodeList(1,arr,None)
            outer=Node(NodeValue(list=ctypes.pointer(nl)),7)
            if lib.mpv_set_option(handle,b"audio-files",6,
                                  ctypes.byref(outer))<0:return False
            if lib.mpv_initialize(handle)<0:return False
            arguments=(ctypes.c_char_p*4)(
                b"loadfile",str(master).encode(),b"replace",None)
            if lib.mpv_command(handle,arguments)<0:return False
            loaded=False
            appended=False
            have_audio=False
            start=time.monotonic()
            while time.monotonic()-start<17:
                event=lib.mpv_wait_event(handle,0.20).contents
                if event.event_id==8:loaded=True
                if event.event_id==7:return False
                if not loaded:continue
                elapsed=time.monotonic()-start
                if not appended and elapsed>=1.5:
                    for clip in clips[2:6]:
                        shutil.copyfile(clip,root/clip.name)
                    snapshot(6)
                    appended=True
                track_count=ctypes.c_int64()
                if lib.mpv_get_property(handle,b"track-list/count",4,
                                        ctypes.byref(track_count))>=0:
                    # Separate AAC selection is also verified by the
                    # dedicated real-libmpv test on this fixture.
                    have_audio=have_audio or track_count.value>=2
                position=ctypes.c_double()
                if lib.mpv_get_property(handle,b"time-pos",5,
                                        ctypes.byref(position))>=0 and (
                                        appended and have_audio and
                                        position.value>7.0):
                    return True
            return False
        finally:
            lib.mpv_terminate_destroy(handle)


if __name__=="__main__":
    if len(sys.argv)!=3:sys.exit(2)
    try:
        sys.exit(0 if check_ready(pathlib.Path(sys.argv[1]),
                                  pathlib.Path(sys.argv[2])) else 1)
    except (OSError,ValueError):
        sys.exit(1)
